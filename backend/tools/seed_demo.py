"""Create a known-good demo corpus: a user, four documents and a few answered chats (T-709).

    cd backend && uv run python -m tools.seed_demo plan          # what it would do, no writes
    cd backend && uv run python -m tools.seed_demo run --yes     # do it

**Why it drives the HTTP API rather than the database.** Every other tool here
(`tools.reembed`, `tools.acceptance`) works in-process against the ORM, and this one
deliberately does not. Seeding through `POST /api/v1/documents` means the demo corpus inherits
FR-KBM-08 dedup, the FR-ERR-02 quota, the 300 MB ceiling, R-33(5) type sniffing, the R-32 scan,
the R-24 processing lock and the whole ingestion pipeline **by construction** rather than by a
second implementation — the same argument R-63(4) used to make cloud import reuse
`upload_document`. It also means what a reviewer reproduces is what a user would have done.

The cost is that this needs a **running API and worker**, which `plan` checks for and says so.

**Repeatable, using the product's own idempotency rather than bookkeeping of its own.**
Re-running converges instead of duplicating: a second upload of identical bytes is FR-KBM-08's
`200 duplicate:true` (no job, no version burned), a second create of the demo user is a `409`,
and conversations are matched by title before being created. Nothing here deletes anything —
a seed script that can destroy a corpus is one nobody dares run twice.

**The documents are generated, never committed.** This repository contains no binary fixtures
at all: `tests/test_recognition.py` synthesises its PDFs with PyMuPDF at runtime, and this
follows it. So the corpus is reproducible byte-for-byte from source, the repo stays free of
blobs nobody can diff, and the table-bearing PDF exercises FR-ING-08's real detector rather
than a file someone once made by hand.

**The scan is skipped loudly when recognition is off, never seeded silently.** Without
`PARSER_OCR_ENABLED` *and* the `ocr` sidecar, an image-only PDF ingests to `FAILED` with
`NO_EXTRACTABLE_TEXT` (R-34) — correct behaviour, and a terrible thing to find unexplained in a
demo corpus a manual is being written against. Both switches are checked and named.

**It changes no settings and writes no configuration.** Turning recognition on is an operator
decision with its own budget arithmetic (`PARSER_OCR_BUDGET_SECONDS` + `OCR_TIMEOUT_SECONDS`
must stay under `WORKER_JOB_TIMEOUT_SECONDS`), and a seed script quietly editing `.env` would
be the worst possible place to discover that.

**Model realism.** The turns are generated by whatever `LLM_BACKEND` names. Against the real
provider the answers read like answers and carry citations, DeepEval chips and scores, which is
what `docs/` screenshots need. Under `LLM_BACKEND=fake` the wiring still runs end to end but the
prose is synthetic — fine as a smoke test, wrong as a screenshot source. `EMBEDDING_BACKEND` is
independent: with `fake` vectors retrieval still works, because R-37's sparse `ts_rank_cd` arm
carries it, and the questions below are worded to be reachable lexically for that reason.
"""

from __future__ import annotations

