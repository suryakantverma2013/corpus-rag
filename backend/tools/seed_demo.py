__all__ = ["main"]

#: Where the API is. The dev default; pass `--base-url http://localhost:8088` for the
#: containerised stack, where only the edge publishes a port (R-81(1)).
DEFAULT_BASE_URL = "http://localhost:8000"

#: How long to wait for the worker to take a document all the way to ACTIVE. Generous, because
#: an OCR page is allowed 60 s of its own and the queue may be busy.
INGEST_TIMEOUT_SECONDS = 300.0
INGEST_POLL_SECONDS = 1.5

#: A turn is ~5-6 s of model latency (R-48), and the graph's own ceiling is
#: GRAPH_NODE_TIMEOUT_SECONDS. This only has to outlast that.
TURN_TIMEOUT_SECONDS = 180.0


# --- the corpus ----------------------------------------------------------------------


@dataclass(frozen=True)
class SeedDocument:
    filename: str
    content_type: str
    build: str  # the builder's name, resolved in `_build`
    why: str  # what this document is *for*, printed by `plan`
    needs_ocr: bool = False


@dataclass(frozen=True)
class SeedChat:
    title: str
    questions: tuple[str, ...]
    why: str


